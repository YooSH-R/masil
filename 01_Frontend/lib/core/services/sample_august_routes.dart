/// 2026년 8월 3~7일 시연용 GPS 경로.
///
/// 그 5일치 산책일지는 **마실이 기기가 S3에 올린 사진·본문만 있고 GPS가 없다.**
/// 산책 없이 일지만 올려 만든 테스트 데이터라서 그렇다. 그대로 두면 시연할 때
/// 그 날짜들만 거리·시간이 비고 경로 지도도 안 그려진다. 그래서 같은 기간의
/// 좌표를 만들어 채운다.
///
/// ## 좌표의 출처
///
/// **실제 측정값이 아니라 만들어 넣은 값이다.** 다만 좌표를 손으로 잇지는
/// 않았다. 처음에는 교차로를 찍고 직선으로 이었는데, 지도에 그려 보니 건물을
/// 관통해서 길을 무시하는 것처럼 보였다. 그래서 7월 예시([SampleWalkDiaries])와
/// 같이 **OSRM 라우팅 서버에서 실제 도보 경로를 받아 심었다.**
///
/// ```
/// https://router.project-osrm.org/route/v1/foot/{경유지들}?overview=full&geometries=geojson
/// ```
///
/// 런타임에 API 를 부르지 않으므로 네트워크·키가 필요 없고 매번 같은 경로가
/// 나온다. 경유지는 멀티캠퍼스 역삼(테헤란로 212 부근, 대략 37.5010 / 127.0374)
/// 주변 큰길 교차로로 잡았고, 모든 경로가 **기점에서 최대 720m** 안에 머물러
/// 도보 5~10분 거리라는 조건에 맞는다.
///
/// 거리·시간은 심어 둔 좌표에서 다시 계산한 값이다(도보 4.3km/h 기준). 라우팅
/// 결과를 60점 이하로 솎아 넣기 때문에 OSRM 이 알려준 거리와 조금 다른데,
/// **지도에 그려진 선 길이와 화면에 뜨는 거리를 맞추는 쪽**을 택했다.
///
/// ## S3 일지와 어떻게 짝지어지나
///
/// S3 일지에는 산책 시각이 없고 **날짜와 회차(session)** 만 있다. 그래서 이
/// 데이터도 같은 키로 들고 있다가, 피드가 일지를 읽을 때 [register] 로
/// walkId(런타임에 계산되는 해시값)를 연결한다. 그 뒤로는 walkId 만으로
/// 경로를 찾을 수 있다.
///
/// ## 제거 방법
///
/// [enabled] 를 false 로 바꾸면 사라진다. 그 날짜에 실제로 걸은 산책이 서버에
/// 생기면 그쪽이 우선이라 이 값은 쓰이지 않는다(피드가 거리·시간이 비어 있는
/// 항목에만 채운다).
class SampleAugustRoutes {
  SampleAugustRoutes._();

  /// 시연용 데이터를 쓸지.
  static const bool enabled = true;

  static const int year = 2026;
  static const int month = 8;

  /// walkId → 그 일지가 며칠 몇 회차인지.
  ///
  /// S3 일지의 walkId 는 deviceId 해시로 런타임에 정해져서 미리 알 수 없다.
  /// 피드가 일지를 읽을 때 채운다.
  static final Map<int, int> _keyByWalkId = {};

  /// 이 날짜·회차의 시연 데이터가 있으면 walkId 와 이어 둔다. 없으면 무시한다.
  static bool register(int walkId, DateTime walkedAt, int session) {
    if (!enabled) return false;
    final key = _keyOf(walkedAt, session);
    if (key == null || !_rows.containsKey(key)) return false;
    _keyByWalkId[walkId] = key;
    return true;
  }

  /// 이 날짜·회차에 채울 값. 없으면 null.
  static SampleAugustRow? rowFor(DateTime walkedAt, int session) {
    if (!enabled) return null;
    final key = _keyOf(walkedAt, session);
    return key == null ? null : _rows[key];
  }

  /// [register] 로 이어 둔 산책의 장소명. 좌표를 역지오코딩하는 대신 직접 넣는다.
  static String? placeOf(int walkId) => _rowOf(walkId)?.place;

  /// 이 산책에 그릴 경로가 있는지. 화면이 `경로 보기` 버튼을 띄울지 정할 때
  /// 쓴다. [summaryFor] 는 좌표 목록을 새로 만들어서 build 안에서 부르기엔 무겁다.
  static bool hasRoute(int walkId) => _keyByWalkId.containsKey(walkId);

  /// 경로 상세 화면이 지도에 선을 그릴 때 쓰는 요약.
  ///
  /// [register] 를 거치지 않은 walkId 면 null 이다. 피드를 한 번도 안 읽고
  /// 상세로 바로 들어오는 경우인데, 앱에서 그 동선은 없다.
  static WalkSummary? summaryFor(int walkId) {
    final key = _keyByWalkId[walkId];
    final row = key == null ? null : _rows[key];
    final coords = key == null ? null : _routes[key];
    if (row == null || coords == null || coords.length < 2) return null;

    final startedAt =
        DateTime.utc(year, month, row.day, row.hour, row.minute);
    final secondsPerStep = (row.minutes * 60) / (coords.length - 1);

    return WalkSummary(
      walkId: walkId,
      durationSeconds: row.minutes * 60,
      distanceMeters: row.meters,
      startedAt: startedAt,
      endedAt: startedAt.add(Duration(minutes: row.minutes)),
      route: [
        for (var i = 0; i < coords.length; i++)
          WalkLocationPoint(
            latitude: coords[i].$1,
            longitude: coords[i].$2,
            sequence: i + 1,
            recordedAt:
                startedAt.add(Duration(seconds: (secondsPerStep * i).round())),
          ),
      ],
    );
  }

  static SampleAugustRow? _rowOf(int walkId) {
    final key = _keyByWalkId[walkId];
    return key == null ? null : _rows[key];
  }

  /// 날짜·회차를 하나의 정수 키로. 8월 3~7일 밖이면 null.
  static int? _keyOf(DateTime walkedAt, int session) {
    if (walkedAt.year != year || walkedAt.month != month) return null;
    if (walkedAt.day < 3 || walkedAt.day > 7) return null;
    if (session < 1) return null;

    // 회차가 준비한 개수를 넘으면 그 날의 첫 경로부터 다시 쓴다. 하루에 일지가
    // 몇 개인지는 S3 데이터에 달려 있어서, 준비한 것보다 많으면 그 항목만
    // 거리·경로가 비어 보인다. 비는 것보다 도는 편이 시연에 낫다.
    final available = _sessionsPerDay[walkedAt.day] ?? 0;
    if (available == 0) return null;
    final normalized = ((session - 1) % available) + 1;
    return walkedAt.day * 10 + normalized;
  }

