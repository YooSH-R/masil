BEGIN;

ALTER TABLE pet_affinity_states
    ADD COLUMN IF NOT EXISTS last_interaction_at TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS version BIGINT NOT NULL DEFAULT 0;

ALTER TABLE pet_affinity_states
    DROP CONSTRAINT IF EXISTS pet_affinity_score_check;

ALTER TABLE pet_affinity_states
    ADD CONSTRAINT pet_affinity_score_check
        CHECK (affinity_score BETWEEN 0 AND 100);

CREATE TABLE IF NOT EXISTS device_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id UUID NOT NULL UNIQUE,
    robot_id BIGINT NOT NULL REFERENCES robots(id),
    event_type VARCHAR(50) NOT NULL,
    payload JSONB NOT NULL DEFAULT '{}'::JSONB,
    previous_score INTEGER NOT NULL,
    score_change INTEGER NOT NULL,
    current_score INTEGER NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT device_events_score_check
        CHECK (
            previous_score BETWEEN 0 AND 100
            AND current_score BETWEEN 0 AND 100
        )
);

CREATE INDEX IF NOT EXISTS idx_device_events_robot_occurred
    ON device_events (robot_id, occurred_at DESC);

CREATE TABLE IF NOT EXISTS behavior_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id UUID NOT NULL UNIQUE,
    robot_id BIGINT NOT NULL REFERENCES robots(id),
    request_type VARCHAR(50) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    message VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ,
    published_at TIMESTAMPTZ,
    received_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    CONSTRAINT behavior_requests_type_check
        CHECK (request_type IN (
            'PLAY_REQUEST',
            'WALK_REQUEST',
            'CARE_REQUEST',
            'INTERACTION_REQUEST'
        )),
    CONSTRAINT behavior_requests_status_check
        CHECK (status IN (
            'PENDING',
            'PUBLISHED',
            'RECEIVED',
            'COMPLETED',
            'REJECTED',
            'EXPIRED'
        ))
);

CREATE INDEX IF NOT EXISTS idx_behavior_requests_robot_status
    ON behavior_requests (robot_id, status, created_at DESC);

COMMIT;
