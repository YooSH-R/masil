BEGIN;

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    email VARCHAR(255),
    password_hash VARCHAR(255),
    nickname VARCHAR(100) NOT NULL,
    phone_number VARCHAR(20),
    phone_verified_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMPTZ,
    CONSTRAINT uq_users_nickname UNIQUE (nickname),
    CONSTRAINT uq_users_phone_number UNIQUE (phone_number)
);

CREATE UNIQUE INDEX uq_users_email_active
    ON users (LOWER(email))
    WHERE email IS NOT NULL AND deleted_at IS NULL;

CREATE TABLE social_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    provider VARCHAR(20) NOT NULL,
    provider_user_id VARCHAR(255) NOT NULL,
    email VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT social_accounts_provider_check
        CHECK (provider IN ('GOOGLE', 'KAKAO', 'NAVER')),
    CONSTRAINT uq_social_provider_user UNIQUE (provider, provider_user_id),
    CONSTRAINT uq_social_user_provider UNIQUE (user_id, provider)
);

CREATE TABLE social_signup_tickets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    provider VARCHAR(20) NOT NULL,
    provider_user_id VARCHAR(255) NOT NULL,
    email VARCHAR(255),
    suggested_nickname VARCHAR(100),
    device_id VARCHAR(255) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    used_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT social_signup_tickets_provider_check
        CHECK (provider IN ('GOOGLE', 'KAKAO', 'NAVER'))
);

CREATE INDEX idx_social_signup_tickets_expires_at
    ON social_signup_tickets (expires_at);

CREATE TABLE auth_verifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    verification_id UUID NOT NULL UNIQUE,
    phone_number VARCHAR(20) NOT NULL,
    purpose VARCHAR(30) NOT NULL,
    code_hash VARCHAR(255) NOT NULL,
    attempt_count INTEGER NOT NULL DEFAULT 0,
    expires_at TIMESTAMPTZ NOT NULL,
    verified_at TIMESTAMPTZ,
    token_hash VARCHAR(64) UNIQUE,
    token_expires_at TIMESTAMPTZ,
    used_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT auth_verifications_purpose_check
        CHECK (purpose IN ('SIGNUP', 'PASSWORD_RESET')),
    CONSTRAINT auth_verifications_attempt_count_check
        CHECK (attempt_count >= 0)
);

CREATE INDEX idx_auth_verifications_phone_created
    ON auth_verifications (phone_number, created_at DESC);

CREATE TABLE auth_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    device_id VARCHAR(255) NOT NULL,
    refresh_token_hash VARCHAR(255) NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_auth_sessions_user_active
    ON auth_sessions (user_id, expires_at)
    WHERE revoked_at IS NULL;

CREATE TABLE pets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    name VARCHAR(100) NOT NULL,
    profile_image_key VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMPTZ
);

CREATE INDEX idx_pets_user_active
    ON pets (user_id, id)
    WHERE deleted_at IS NULL;

CREATE TABLE pet_creation_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    idempotency_key VARCHAR(100) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    pet_id BIGINT NOT NULL REFERENCES pets(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_pet_creation_requests_user_key
        UNIQUE (user_id, idempotency_key)
);

CREATE TABLE pet_affinity_states (
    pet_id BIGINT PRIMARY KEY REFERENCES pets(id) ON DELETE CASCADE,
    affinity_score INTEGER NOT NULL DEFAULT 0,
    affinity_level INTEGER NOT NULL DEFAULT 1,
    mood VARCHAR(30) NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pet_affinity_score_check CHECK (affinity_score >= 0),
    CONSTRAINT pet_affinity_level_check CHECK (affinity_level >= 1)
);

CREATE TABLE robots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    serial_number VARCHAR(100) NOT NULL UNIQUE,
    model_name VARCHAR(100) NOT NULL,
    firmware_version VARCHAR(50),
    owner_user_id BIGINT REFERENCES users(id),
    ownership_claimed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT robots_ownership_claim_check
        CHECK (
            (owner_user_id IS NULL AND ownership_claimed_at IS NULL)
            OR (owner_user_id IS NOT NULL AND ownership_claimed_at IS NOT NULL)
        )
);

CREATE TABLE robot_credentials (
    robot_id BIGINT PRIMARY KEY REFERENCES robots(id) ON DELETE CASCADE,
    device_token_hash VARCHAR(255) UNIQUE,
    device_token_expires_at TIMESTAMPTZ,
    device_token_rotated_at TIMESTAMPTZ,
    qr_token_hash VARCHAR(64) NOT NULL UNIQUE,
    qr_token_expires_at TIMESTAMPTZ,
    qr_token_last_used_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE robot_pairings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pet_id BIGINT NOT NULL REFERENCES pets(id),
    robot_id BIGINT NOT NULL REFERENCES robots(id),
    paired_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    unpaired_at TIMESTAMPTZ,
    CONSTRAINT robot_pairings_period_check
        CHECK (unpaired_at IS NULL OR unpaired_at >= paired_at)
);

CREATE UNIQUE INDEX uq_robot_pairings_active_robot
    ON robot_pairings (robot_id)
    WHERE unpaired_at IS NULL;

CREATE UNIQUE INDEX uq_robot_pairings_active_pet
    ON robot_pairings (pet_id)
    WHERE unpaired_at IS NULL;

CREATE INDEX idx_robot_pairings_pet_lookup
    ON robot_pairings (pet_id, id);

CREATE TABLE robot_current_states (
    robot_id BIGINT PRIMARY KEY REFERENCES robots(id) ON DELETE CASCADE,
    online BOOLEAN NOT NULL DEFAULT FALSE,
    mode VARCHAR(30) NOT NULL,
    battery_level INTEGER NOT NULL DEFAULT 0,
    docked BOOLEAN NOT NULL DEFAULT FALSE,
    last_seen_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT robot_battery_level_check
        CHECK (battery_level BETWEEN 0 AND 100)
);

CREATE TABLE walk_proposals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    robot_pairing_id BIGINT NOT NULL REFERENCES robot_pairings(id),
    message VARCHAR(500) NOT NULL,
    status VARCHAR(30) NOT NULL,
    proposed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ,
    responded_at TIMESTAMPTZ,
    CONSTRAINT walk_proposals_status_check
        CHECK (status IN ('PENDING', 'ACCEPTED', 'DECLINED', 'EXPIRED')),
    CONSTRAINT walk_proposals_expiry_check
        CHECK (expires_at IS NULL OR expires_at > proposed_at),
    CONSTRAINT walk_proposals_response_check
        CHECK (
            (status IN ('ACCEPTED', 'DECLINED') AND responded_at IS NOT NULL)
            OR
            (status IN ('PENDING', 'EXPIRED') AND responded_at IS NULL)
        )
);

CREATE UNIQUE INDEX uq_walk_proposals_pairing_pending
    ON walk_proposals (robot_pairing_id)
    WHERE status = 'PENDING';

CREATE INDEX idx_walk_proposals_current
    ON walk_proposals (robot_pairing_id, proposed_at DESC, id DESC);

CREATE INDEX idx_walk_proposals_pending_expires
    ON walk_proposals (expires_at)
    WHERE status = 'PENDING' AND expires_at IS NOT NULL;

CREATE TABLE walks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    robot_pairing_id BIGINT NOT NULL REFERENCES robot_pairings(id),
    proposal_id BIGINT UNIQUE REFERENCES walk_proposals(id),
    status VARCHAR(30) NOT NULL,
    started_at TIMESTAMPTZ,
    ended_at TIMESTAMPTZ,
    distance_meters NUMERIC(10, 2),
    duration_seconds INTEGER,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT walks_distance_check
        CHECK (distance_meters IS NULL OR distance_meters >= 0),
    CONSTRAINT walks_duration_check
        CHECK (duration_seconds IS NULL OR duration_seconds >= 0),
    CONSTRAINT walks_status_check
        CHECK (
            status IN (
                'READY',
                'ACTIVE',
                'PROCESSING',
                'COMPLETED',
                'CANCELLED'
            )
        ),
    CONSTRAINT walks_time_order_check
        CHECK (
            ended_at IS NULL
            OR (started_at IS NOT NULL AND ended_at >= started_at)
        ),
    CONSTRAINT walks_lifecycle_check
        CHECK (
            (status = 'READY' AND started_at IS NULL AND ended_at IS NULL)
            OR (status = 'ACTIVE' AND started_at IS NOT NULL AND ended_at IS NULL)
            OR (status = 'PROCESSING' AND started_at IS NOT NULL AND ended_at IS NOT NULL)
            OR (
                status = 'COMPLETED'
                AND started_at IS NOT NULL
                AND ended_at IS NOT NULL
                AND distance_meters IS NOT NULL
                AND duration_seconds IS NOT NULL
            )
            OR status = 'CANCELLED'
        )
);

CREATE UNIQUE INDEX uq_walks_pairing_open
    ON walks (robot_pairing_id)
    WHERE status IN ('READY', 'ACTIVE', 'PROCESSING');

CREATE INDEX idx_walks_pairing_created
    ON walks (robot_pairing_id, created_at DESC, id DESC);

CREATE INDEX idx_walks_pairing_completed_ended
    ON walks (robot_pairing_id, ended_at DESC)
    WHERE status = 'COMPLETED';

CREATE INDEX idx_walks_pairing_lookup
    ON walks (robot_pairing_id, id);

CREATE TABLE robot_photos (
    id UUID PRIMARY KEY,
    robot_id BIGINT NOT NULL REFERENCES robots(id),
    object_key VARCHAR(500) NOT NULL UNIQUE,
    upload_status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    mime_type VARCHAR(100) NOT NULL,
    expected_size_bytes BIGINT NOT NULL,
    actual_size_bytes BIGINT,
    captured_at TIMESTAMPTZ NOT NULL,
    upload_expires_at TIMESTAMPTZ NOT NULL,
    uploaded_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT robot_photos_status_check
        CHECK (upload_status IN ('PENDING', 'UPLOADED', 'EXPIRED')),
    CONSTRAINT robot_photos_expected_size_check
        CHECK (expected_size_bytes BETWEEN 1 AND 10485760),
    CONSTRAINT robot_photos_actual_size_check
        CHECK (actual_size_bytes IS NULL OR actual_size_bytes >= 0)
);

CREATE INDEX idx_robot_photos_robot_created
    ON robot_photos (robot_id, created_at DESC);

CREATE TABLE walk_locations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    walk_id BIGINT NOT NULL REFERENCES walks(id) ON DELETE CASCADE,
    sequence_no INTEGER NOT NULL,
    latitude NUMERIC(10, 7) NOT NULL,
    longitude NUMERIC(10, 7) NOT NULL,
    accuracy_meters NUMERIC(8, 2),
    recorded_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_walk_locations_sequence UNIQUE (walk_id, sequence_no),
    CONSTRAINT walk_locations_latitude_check
        CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT walk_locations_longitude_check
        CHECK (longitude BETWEEN -180 AND 180),
    CONSTRAINT walk_locations_sequence_check
        CHECK (sequence_no >= 0),
    CONSTRAINT walk_locations_accuracy_check
        CHECK (
            accuracy_meters IS NULL
            OR accuracy_meters BETWEEN 0 AND 50
        )
);

CREATE TABLE walk_location_batch_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    walk_id BIGINT NOT NULL REFERENCES walks(id) ON DELETE CASCADE,
    idempotency_key VARCHAR(100) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    received_count INTEGER NOT NULL,
    saved_count INTEGER NOT NULL,
    rejected_count INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_walk_location_batch_request
        UNIQUE (walk_id, idempotency_key),
    CONSTRAINT walk_location_batch_counts_check
        CHECK (
            received_count >= 0
            AND saved_count >= 0
            AND rejected_count >= 0
            AND saved_count + rejected_count <= received_count
        )
);

CREATE INDEX idx_walk_location_batch_requests_created
    ON walk_location_batch_requests (created_at, id);

CREATE TABLE walk_photos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    walk_id BIGINT NOT NULL REFERENCES walks(id) ON DELETE CASCADE,
    walk_location_id BIGINT REFERENCES walk_locations(id) ON DELETE SET NULL,
    sequence_no INTEGER NOT NULL,
    storage_provider VARCHAR(30) NOT NULL,
    object_key VARCHAR(500) NOT NULL,
    mime_type VARCHAR(100) NOT NULL,
    file_size_bytes BIGINT,
    checksum VARCHAR(128),
    captured_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_walk_photos_sequence UNIQUE (walk_id, sequence_no),
    CONSTRAINT walk_photos_file_size_check
        CHECK (file_size_bytes IS NULL OR file_size_bytes >= 0)
);

CREATE TABLE photo_analyses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    photo_id BIGINT NOT NULL UNIQUE REFERENCES walk_photos(id) ON DELETE CASCADE,
    processing_status VARCHAR(30) NOT NULL,
    caption TEXT,
    model_name VARCHAR(100),
    prompt_version VARCHAR(50),
    retry_count INTEGER NOT NULL DEFAULT 0,
    error_code VARCHAR(100),
    processed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT photo_analyses_retry_count_check CHECK (retry_count >= 0)
);
CREATE TABLE push_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    device_id VARCHAR(255) NOT NULL,
    platform VARCHAR(20) NOT NULL,
    token VARCHAR(500) NOT NULL UNIQUE,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_push_tokens_user_device UNIQUE (user_id, device_id)
);

CREATE TABLE notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    notification_type VARCHAR(50) NOT NULL,
    title VARCHAR(200) NOT NULL,
    body VARCHAR(1000) NOT NULL,
    data JSONB,
    read_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_notifications_user_created
    ON notifications (user_id, created_at DESC);

COMMIT;
