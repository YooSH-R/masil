///
/// 백엔드 산책 API 가 아직 없어서, 달력·상세 기록·주간/월간 통계·경로 지도가
/// 실제로 어떻게 보이는지 확인하고 시연하기 위한 데이터다.
///
/// **8월 이후 데이터는 실제 산책으로 생성된다.** 이 데이터는 7월만 채우고,
/// 서버에서 받은 기록과 합쳐진다(같은 날짜가 겹치면 서버 것이 우선).
///
/// ## 경로 좌표의 출처
///
/// 처음에는 기준 좌표에서 방향을 꺾어가며 좌표를 계산해 만들었는데, 도로를
/// 무시하고 건물을 관통해서 보기 나빴다. 그래서 **OSRM 라우팅 서버에서 실제
/// 도로를 따라가는 경로를 받아 좌표를 그대로 심었다.**
///
/// ```
/// https://router.project-osrm.org/route/v1/foot/{경유지들}?overview=full&geometries=geojson
/// ```
///
/// 런타임에 API 를 부르지 않으므로 네트워크·키가 필요 없고 매번 같은 경로가
/// 나온다. 거리·시간도 라우팅 결과에서 가져온 값이라 지도에 그려진 선 길이와
/// 화면에 표시되는 거리가 일치한다.
///
/// ## 제거 방법
/// [enabled] 를 false 로 바꾸면 앱에서 사라진다. 서버에 7월 데이터가 들어오면
/// 이 파일과 [WalkDiaryViewModel] 의 병합 코드, [WalkViewModel.loadSummary] 의
/// 예시 분기를 지우면 된다.
