  /// 예시 산책의 경로 요약. 경로 상세 화면이 이걸로 지도에 선을 그린다.
  static WalkSummary? summaryFor(int walkId) {
    final row = _rowOf(walkId);
    final coords = _routes[walkId];
    if (row == null || coords == null) return null;

    final startedAt = DateTime(year, month, row.day, row.hour, row.minute);
    final secondsPerStep = coords.length < 2
        ? 0.0
        : (row.minutes * 60) / (coords.length - 1);

    return WalkSummary(
      walkId: walkId,
      durationSeconds: row.minutes * 60,
      distanceMeters: row.meters,
      startedAt: startedAt,
      endedAt: startedAt.add(Duration(minutes: row.minutes)),
      route: [
        for (var i = 0; i < coords.length; i++)
          WalkLocationPoint(
            latitude: coords[i].$1,
            longitude: coords[i].$2,
            sequence: i + 1,
            recordedAt:
                startedAt.add(Duration(seconds: (secondsPerStep * i).round())),
          ),
      ],
    );
  }

