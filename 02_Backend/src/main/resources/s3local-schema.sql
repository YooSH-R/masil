CREATE TABLE pets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    name VARCHAR(100) NOT NULL,
    deleted_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE robots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    serial_number VARCHAR(100) NOT NULL UNIQUE,
    model_name VARCHAR(100) NOT NULL
);

CREATE TABLE robot_credentials (
    robot_id BIGINT PRIMARY KEY REFERENCES robots(id),
    device_token_hash VARCHAR(255) NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE robot_pairings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    pet_id BIGINT NOT NULL REFERENCES pets(id),
    robot_id BIGINT NOT NULL REFERENCES robots(id),
    paired_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    unpaired_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE robot_photos (
    id UUID PRIMARY KEY,
    robot_id BIGINT NOT NULL REFERENCES robots(id),
    object_key VARCHAR(500) NOT NULL UNIQUE,
    upload_status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    mime_type VARCHAR(100) NOT NULL,
    expected_size_bytes BIGINT NOT NULL,
    actual_size_bytes BIGINT,
    captured_at TIMESTAMP WITH TIME ZONE NOT NULL,
    upload_expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    uploaded_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

