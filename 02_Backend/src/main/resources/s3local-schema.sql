CREATE TABLE IF NOT EXISTS pet_affinity_states (
    pet_id BIGINT PRIMARY KEY REFERENCES pets(id),
    affinity_score INTEGER NOT NULL DEFAULT 0,
    affinity_level INTEGER NOT NULL DEFAULT 1,
    mood VARCHAR(30) NOT NULL DEFAULT 'CALM',
    last_interaction_at TIMESTAMP WITH TIME ZONE,
    version BIGINT NOT NULL DEFAULT 0,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE pet_affinity_states
    ADD COLUMN IF NOT EXISTS last_interaction_at TIMESTAMP WITH TIME ZONE;
ALTER TABLE pet_affinity_states
    ADD COLUMN IF NOT EXISTS version BIGINT NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS robot_current_states (
    robot_id BIGINT PRIMARY KEY REFERENCES robots(id),
    online BOOLEAN NOT NULL DEFAULT FALSE,
    mode VARCHAR(30) NOT NULL,
    battery_level INTEGER NOT NULL DEFAULT 0,
    docked BOOLEAN NOT NULL DEFAULT FALSE,
    last_seen_at TIMESTAMP WITH TIME ZONE,
    last_message_id UUID,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE robot_current_states
    ADD COLUMN IF NOT EXISTS last_message_id UUID;

CREATE TABLE IF NOT EXISTS device_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id UUID NOT NULL UNIQUE,
    robot_id BIGINT NOT NULL REFERENCES robots(id),
    event_type VARCHAR(50) NOT NULL,
    payload JSON NOT NULL,
    previous_score INTEGER NOT NULL,
    score_change INTEGER NOT NULL,
    current_score INTEGER NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS behavior_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id UUID NOT NULL UNIQUE,
    robot_id BIGINT NOT NULL REFERENCES robots(id),
    request_type VARCHAR(50) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    message VARCHAR(500),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMP WITH TIME ZONE,
    published_at TIMESTAMP WITH TIME ZONE,
    received_at TIMESTAMP WITH TIME ZONE,
    completed_at TIMESTAMP WITH TIME ZONE,
    last_result_message_id UUID
);

CREATE TABLE IF NOT EXISTS walks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    robot_pairing_id BIGINT NOT NULL REFERENCES robot_pairings(id),
    proposal_id BIGINT,
    status VARCHAR(30) NOT NULL,
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    ended_at TIMESTAMP WITH TIME ZONE,
    distance_meters NUMERIC(10, 2),
    duration_seconds INTEGER,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_robot_pairings_pet_lookup
    ON robot_pairings (pet_id, id);

CREATE INDEX IF NOT EXISTS idx_walks_pairing_lookup
    ON walks (robot_pairing_id, id);

